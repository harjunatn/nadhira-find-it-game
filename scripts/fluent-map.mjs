// Regenerates src/lib/fluent.js, the emoji → Fluent 3D picture table.
// Usage: node scripts/fluent-map.mjs         only the emoji the game uses (scenes + hiding spots)
//        node scripts/fluent-map.mjs --all   every emoji that has a 3D picture
import fs from 'node:fs';
import path from 'node:path';
import { importBundled, root } from './bundle.mjs';

const COMMIT = '1ffb34c752ecf5d402f04cfb4b392c77f57c54bc';
const all = process.argv.includes('--all');

const tree = await (await fetch(`https://api.github.com/repos/microsoft/fluentui-emoji/git/trees/${COMMIT}?recursive=1`)).json();
const names = await (await fetch('https://cdn.jsdelivr.net/npm/unicode-emoji-json@0.6.0/data-by-emoji.json')).json();
if (!tree.tree) throw new Error(`GitHub API: ${JSON.stringify(tree).slice(0, 200)}`);

// Folder name (lower case) → path of its 3D picture. People emoji keep the default skin tone.
const byFolder = new Map();
for (const { path: p } of tree.tree) {
  if (!p.endsWith('.png')) continue;
  const parts = p.split('/');
  const plain = parts.length === 4 && parts[2] === '3D';
  const skin = parts.length === 5 && parts[2] === 'Default' && parts[3] === '3D';
  if (plain || skin) byFolder.set(parts[1].toLowerCase(), p.slice('assets/'.length));
}

const norm = (e) => e.replace(/️/g, '');
const table = new Map();
for (const [emoji, info] of Object.entries(names)) {
  const name = (info.name || '').toLowerCase();
  const file = byFolder.get(name) || byFolder.get(name.replace(/[^a-z0-9 ]/g, '')) || byFolder.get(name.replace(/:/g, ''));
  if (file) table.set(norm(emoji), file);
}

let wanted;
if (all) {
  wanted = [...table.keys()];
} else {
  const { BUILTIN_SCENES, HIDING_SPOTS } = await importBundled(
    `export { BUILTIN_SCENES } from '../src/scenes/index.js'; export { HIDING_SPOTS } from '../src/lib/hard.js';`,
    'fluent',
  );
  const used = new Set(HIDING_SPOTS.map(norm));
  for (const s of BUILTIN_SCENES) {
    for (const o of s.objects) if (o.emoji) used.add(norm(o.emoji));
    for (const e of s.hideBehind || []) used.add(norm(e));
  }
  const missing = [...used].filter((e) => !table.has(e));
  if (missing.length) console.warn(`No 3D picture for: ${missing.join(' ')}`);
  wanted = [...used].filter((e) => table.has(e));
}

const lines = wanted
  .sort()
  .map((e) => `  '${e}': '${table.get(e).replace(/'/g, "\\'")}',`)
  .join('\n');
const out = `// 3D pictures for emoji objects, from Microsoft Fluent Emoji (MIT licence):
// https://github.com/microsoft/fluentui-emoji — pinned to one commit and served by jsDelivr.
// Generated by scripts/fluent-map.mjs. Emoji not listed here are drawn with the device's emoji font.

const BASE = 'https://cdn.jsdelivr.net/gh/microsoft/fluentui-emoji@${COMMIT}/assets/';

const FILES = {
${lines}
};

export function hasFluent(emoji) {
  return !!FILES[emoji.replace(/\\uFE0F/g, '')];
}

export function fluentUrl(emoji) {
  const file = FILES[emoji.replace(/\\uFE0F/g, '')];
  return file ? BASE + encodeURI(file) : null;
}
`;
fs.writeFileSync(path.join(root, 'src/lib/fluent.js'), out);
console.log(`wrote ${wanted.length} entries to src/lib/fluent.js`);
